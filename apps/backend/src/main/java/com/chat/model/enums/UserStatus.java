package com.chat.model.enums;

/**
 * User online status
 */
public enum UserStatus {
    /**
     * User is currently online and active
     */
    ONLINE,

    /**
     * User is offline
     */
    OFFLINE,

    /**
     * User is away from keyboard
     */
    AWAY,

    /**
     * User is busy, do not disturb
     */
    BUSY
}
